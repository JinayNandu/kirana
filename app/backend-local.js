// ---------------------------------------------------------------------
//  runs
//
//  Derived from the timetable, then overlaid with whatever was
//  actually written. Tomorrow's runs exist the instant the IST clock
//  passes midnight: no cron, no generate button, no empty table. Only
//  the delta is stored, so most days write nothing at all.
// ---------------------------------------------------------------------
const runOverlay = () => read(K.runs, {});

export const runs = {
  async forDate(date){
    const d = await DATA;
    const stored = runOverlay();
    return d.slots.map((s) => ({ ...deriveRun(date, s), ...(stored['run-' + date + '-' + s.id] || {}) }));
  },

  async byId(id){
    const m = /^run-(\d{4}-\d{2}-\d{2})-(\w+)$/.exec(id || '');
    if (!m) return null;
    const list = await runs.forDate(m[1]);
    return list.find((r) => r.id === id) || null;
  },


  // Today's remaining plus all of tomorrow's. Two days, because a
  // kirana does not take orders for Thursday and two days keeps the
  // picker to one screen.
  async bookable(){
    const now = new Date();
    const today = istDate(now), m = istMins(now);
    const out = [];
    for (const date of [today, addDays(today, 1)]){
      for (const r of await runs.forDate(date)){
        if (!r.enabled) continue;
        const open = isBookable(r, today, m);
        const n = (await runs.ordersOf(r.id)).length;
        // A full or closed run is SHOWN, not hidden -- a slot that
        // silently vanishes reads as a broken app, one that says why
        // reads as a busy shop.
        if (date === today && !open) continue;
        out.push({ ...r, taken: n, left: r.cap - n, full: n >= r.cap });
      }
    }
    return out;
  },

  async today(){
    const now = new Date();
    const today = istDate(now), m = istMins(now);
    const list = await runs.forDate(today);
    const out = [];
    for (const r of list){
      const n = await runs.counts(r.id);
      out.push({ ...r, state: runState(r, today, m), ...n });
    }
    return out;
  },

  async ordersOf(runId){
    return read(K.orders, []).filter((o) => o.runId === runId && o.status !== 'cancelled');
  },

  async setStatus(runId, to){
    const r = await runs.byId(runId);
    if (!r) throw new Error('NO_SUCH_RUN');
    const from = runState(r, istDate(), istMins());
    if (!canAdvanceRun(from, to)) throw new Error('BAD_RUN_STATE:' + from + '>' + to);
    const patch = { status: to };
    if (to === 'cutoff')  patch.closedAt  = new Date().toISOString();
    if (to === 'done')    patch.doneAt    = new Date().toISOString();
    return runs.patch(runId, patch);
  },

  async patch(runId, patch){
    let out = null;
    commit('runs', K.runs, (cur) => {
      const m = (cur && !Array.isArray(cur)) ? cur : {};
      m[runId] = { ...(m[runId] || {}), ...patch };
      out = m[runId];
      return m;
    });
    return clone(out);
  },


  // What to load into the tempo: every product summed across every
  // order on the run. This is the only arithmetic in the app a human
  // cannot check by eye, which is why money.pl covers it.
  async load(runId){
    const d = await DATA;
    const list = await runs.ordersOf(runId);
    const agg = new Map();
    for (const o of list){
      for (const l of o.lines){
        const cur = agg.get(l.pid) || { pid: l.pid, qty: 0, orders: 0 };
        cur.qty += l.qty;
        cur.orders += 1;
        agg.set(l.pid, cur);
      }
    }
    const rows = [...agg.values()].map((r) => {
      const p = d.byId[r.pid];
      return { ...r, cat: p ? p.cat : 'other', product: clone(p) || null };
    });
    // Grouped the way the shelves are arranged, not alphabetically.
    const order = {};
    d.categories.forEach((c, i) => { order[c.id] = i; });
    rows.sort((a, b) => (order[a.cat] ?? 99) - (order[b.cat] ?? 99)
      || (a.product?.brand || '').localeCompare(b.product?.brand || ''));
    return rows;
  },

  async counts(runId){
    const list = await runs.ordersOf(runId);
    const byStatus = {};
    let items = 0, cash = 0, paidTotal = 0, paidCount = 0;
    let saidTotal = 0, saidCount = 0;
    for (const o of list){
      byStatus[o.status] = (byStatus[o.status] || 0) + 1;
      for (const l of o.lines) items += l.qty;
      // What the shop still has to collect is what nobody has
      // VERIFIED, whatever the delivery status -- UPI can land before
      // the order leaves or the morning after. A customer's "I have
      // paid" is a claim, so it stays in `cash`; saidTotal is how
      // much of that the customer says is already paid.
      const ps = payState(o);
      if (ps === 'verified'){ paidTotal += o.grand; paidCount++; }
      else cash += o.grand;
      if (ps === 'said'){ saidTotal += o.grand; saidCount++; }
    }
    return {
      orders: list.length, items, cash, paidTotal, paidCount,
      saidTotal, saidCount, byStatus,
    };
  },
};

// ---------------------------------------------------------------------
//  places -- the address book
//
//  SEVERAL addresses per person, each carrying its OWN name and phone,
//  because "where does it go" and "who takes it in" are two questions
//  and the app was asking one. Groceries to the flat go to you;
//  groceries to your mother's go to her, and the number the driver
//  rings has to be hers or the delivery fails at the door.
//
//  AN ORDER NEVER REFERENCES ONE OF THESE. place() copies the fields
//  into the order, which is the same rule as the price on a cart line
//  and for the same reason: an address edited or deleted next month
//  must not rewrite where last week's order went.
// ---------------------------------------------------------------------
export const places = {
  async list(){
    // Default first, then newest. The one used most should not move
    // around the screen between visits.
    return clone(read(K.places, []).slice().sort((a, b) =>
      (b.isDefault ? 1 : 0) - (a.isDefault ? 1 : 0)
      || String(b.at || '').localeCompare(String(a.at || ''))));
  },

  async get(id){
    return clone(read(K.places, []).find((a) => a.id === id) || null);
  },

  async save(a){
    const all = read(K.places, []);
    const now = new Date().toISOString();
    let row;
    if (a.id){
      const i = all.findIndex((x) => x.id === a.id);
      if (i < 0) throw new Error('NO_SUCH_ADDRESS');
      row = { ...all[i], ...a };
      all[i] = row;
    } else {
      // Ids are minted by the backend and never by the UI -- the
      // third of the four rules that keep the Supabase swap to one
      // import line.
      row = {
        ...a,
        id: 'adr-' + Date.now().toString(36) + Math.random().toString(36).slice(2, 6),
        at: now,
      };
      // The first address saved is the default. There is nothing to
      // choose between when there is one.
      if (!all.length) row.isDefault = true;
      all.push(row);
    }
    if (row.isDefault) for (const x of all) if (x.id !== row.id) x.isDefault = false;
    write(K.places, all);
    return clone(row);
  },

  async remove(id){
    const all = read(K.places, []).filter((a) => a.id !== id);
    // Deleting the default promotes the next one rather than leaving
    // the book with nothing chosen, which would show an order screen
    // with no address selected and no way to tell why.
    if (all.length && !all.some((a) => a.isDefault)) all[0].isDefault = true;
    write(K.places, all);
  },

  async setDefault(id){
    const all = read(K.places, []);
    for (const a of all) a.isDefault = (a.id === id);
    write(K.places, all);
  },
};

// ---------------------------------------------------------------------
//  orders
// ---------------------------------------------------------------------
function nextSeq(){
  let n = 0;
  try { n = parseInt(localStorage.getItem(K.seq) || '0', 10) || 0; } catch {}
  n += 1;
  try { localStorage.setItem(K.seq, String(n)); } catch {}
  return n;
}

export const orders = {
  async all(){ return read(K.orders, []); },
  async mine(){ return read(K.orders, []).slice().reverse(); },
  async byId(id){ return read(K.orders, []).find((o) => o.id === id) || null; },

  // "Buy it again" -- what this device has ordered before, newest
  // first, minus whatever is already in the basket.
  //
  // Deliberately NOT merged with catalog.suggest(): that one answers
  // "what goes with this basket", this one answers "what do you
  // usually get". They overlap often and that is fine -- a customer
  // who buys milk every week and has just added tea should see milk
  // twice over, not have one list quietly suppress the other.
  async againItems(limit){
    const d = await DATA;
    const inCart = new Set(read(K.cart, []).map((l) => l.pid));
    const seen = new Set();
    const out = [];
    for (const o of read(K.orders, []).slice().reverse()){
      for (const l of o.lines){
        if (seen.has(l.pid) || inCart.has(l.pid)) continue;
        seen.add(l.pid);
        const p = d.byId[l.pid];
        if (p && p.stock) out.push(clone(p));
        if (out.length >= (limit || 8)) return out;
      }
    }
    return out;
  },

  async forRun(runId){
    const list = read(K.orders, []).filter((o) => o.runId === runId);
    // Unsequenced orders go LAST, never hidden.
    return list.sort((a, b) => (a.seq ?? 9999) - (b.seq ?? 9999));
  },

  // The cut-off is enforced HERE, in the data layer, and not in the
  // picker -- a customer can sit on the address screen across a
  // cut-off, and the Supabase version will put this same check in a
  // Postgres function.
  async place(draft){
    const d = await DATA;
    const run = await runs.byId(draft.runId);
    if (!run) throw new Error('NO_SUCH_RUN');
    if (!run.enabled) throw new Error('RUN_CLOSED');
    if (!isBookable(run, istDate(), istMins())) throw new Error('RUN_CLOSED');

    const already = await runs.ordersOf(run.id);
    if (already.length >= run.cap) throw new Error('RUN_FULL');

    const raw = read(K.cart, []);
    if (!raw.length) throw new Error('CART_EMPTY');

    // Snapshot: the one moment a price must freeze.
    const lines = [];
    const b2g1 = new Set((d.offers && d.offers.b2g1) || []);
    for (const l of raw){
      const p = d.byId[l.pid];
      if (!p) continue;
      lines.push({
        pid: p.id,
        // Same rule as pname(): never "Parle Parle-G", never "Shop Onion".
        nameEn: (p.brand && p.brand !== 'Shop'
                 && p.name.en.toLowerCase().indexOf(p.brand.toLowerCase()) !== 0)
                ? p.brand + ' ' + p.name.en : p.name.en,
        pack: { ...p.pack },
        qty: l.qty,
        unitPrice: p.price,
        unitMrp: p.mrp,
        // NET of the offer, and from the SAME freeUnits() the basket
        // total uses. A line total that does its own arithmetic is
        // how a receipt ends up disagreeing with the figure printed
        // underneath it -- three packets at 20 listed as 60, over a
        // total of 40 -- and once an order is stored with both
        // numbers in it there is no way to say which was right.
        lineTotal: p.price * (l.qty - (b2g1.has(p.id) ? freeUnits(l.qty) : 0)),
      });
    }
    if (!lines.length) throw new Error('CART_EMPTY');

    // Re-matched at placement, not trusted from the cart: a code
    // withdrawn between adding it and ordering must not still apply.
    const coupon = matchCoupon(read(K.coupon, null), d.coupons);
    const t = calcTotals(raw, d.byId, d.delivery, coupon, d.offers);
    if (t.short > 0) throw new Error('BELOW_MIN');

    const n = nextSeq();
    const now = new Date().toISOString();
    const order = {
      id: 'ord-' + istDate() + '-' + String(n).padStart(4, '0'),
      // The shop's own letter, out of shop.json. db/schema.sql has
      // to carry the same one, because a Postgres generated column
      // cannot read a JSON file; data.pl checks that they agree.
      code: (d.shop.orderPrefix || 'K') + '-' + String(n).padStart(4, '0'),
      placedAt: now,
      runId: run.id,
      // Free text, because the shop delivers wherever the customer is
      // and a driver reads an address rather than a zone id. `ll` is
      // there only if the customer tapped "use my location"; it is a
      // help to the driver, never a substitute for the words.
      customer: {
        name: draft.name, phone: draft.phone,
        flat: draft.flat, society: draft.society, area: draft.area,
        landmark: draft.landmark || '',
        ll: draft.ll || null,
      },
      lines,
      itemsTotal: t.items, mrpTotal: t.mrp, saved: t.saved,
      coupon: t.coupon, couponPercent: t.couponPercent, discount: t.discount,
      fee: t.fee, grand: t.grand,
      // The app cannot KNOW that a UPI payment happened -- there is no
      // callback to a static page. So this is a note somebody makes,
      // not a fact the app observed, and both sides can set it.
      paid: false, paidAt: null, paidVia: null,
      payMethod: null,   // 'upi' | 'cod', chosen after placing
      status: 'placed',
      seq: null,
      history: [{ at: now, to: 'placed' }],
      note: draft.note || '',
    };

    commit('orders', K.orders, (list) => list.concat([order]));
    await cart.clear();
    await profile.save({
      name: draft.name, phone: draft.phone,
      flat: draft.flat, society: draft.society, area: draft.area,
      landmark: draft.landmark || '', ll: draft.ll || null,
    });
    return clone(order);
  },

  // Invalid transitions THROW. A silent no-op is a button that looks
  // like it worked.
  // Re-price from the catalogue, never from what the browser sent.
  // An order's line total is the one number a customer could profit
  // from choosing, and `place()` already treats placement as the
  // moment a price freezes -- an edit is a second such moment, not
  // an excuse to trust a figure that arrived from a screen.
  async edit(id, lines){
    const d = await ready();
    const want = (lines || []).filter((l) => l.qty > 0);
    if (!want.length) throw new Error('EMPTY');
    let err = null, out = null;
    commit('orders', K.orders, (list) => list.map((o) => {
      if (o.id !== id) return o;
      if (o.status !== 'placed' && o.status !== 'accepted'){
        err = 'TOO_LATE'; return o;
      }
      const b2g1 = new Set((d.offers && d.offers.b2g1) || []);
      const keep = [];
      for (const w of want){
        const was = o.lines.find((l) => l.pid === w.pid);
        const p = d.byId[w.pid];
        if (!was || !p) continue;
        const free = b2g1.has(w.pid) ? freeUnits(w.qty) : 0;
        keep.push({ ...was, qty: w.qty,
          lineTotal: p.price * (w.qty - free) });
      }
      if (!keep.length){ err = 'EMPTY'; return o; }
      const coupon = matchCoupon(o.coupon, d.coupons);
      const t = calcTotals(keep.map((l) => ({ pid: l.pid, qty: l.qty })),
        d.byId, d.delivery, coupon, d.offers);
      out = { ...o, lines: keep,
        itemsTotal: t.items, mrpTotal: t.mrp, saved: t.saved,
        discount: t.discount, fee: t.fee, grand: t.grand,
        history: o.history.concat(
          [{ at: new Date().toISOString(), to: 'edited', note: '' }]) };
      return out;
    }));
    if (err) throw new Error(err);
    if (!out) throw new Error('NO_SUCH_ORDER');
    return clone(out);
  },

  async advance(id, to, note){
    let err = null, out = null;
    commit('orders', K.orders, (list) => list.map((o) => {
      if (o.id !== id) return o;
      if (!canAdvance(o.status, to)){ err = 'BAD_STATE:' + o.status + '>' + to; return o; }
      out = {
        ...o, status: to,
        history: o.history.concat([{ at: new Date().toISOString(), to, note: note || '' }]),
      };
      return out;
    }));
    if (err) throw new Error(err);
    if (!out) throw new Error('NO_SUCH_ORDER');
    return clone(out);
  },

  async cancel(id, reason){ return orders.advance(id, 'cancelled', reason); },

  // Marking an order paid is independent of its delivery status: money
  // can arrive before the tempo leaves, at the door, or the next
  // morning. Keeping the two apart is why there is no 'paid' state in
  // ORDER_NEXT.
  // How the customer SAYS they will pay. Separate from `paid`, which
  // is whether the money has actually turned up.
  async setPayMethod(id, method){
    let out = null;
    commit('orders', K.orders, (list) => list.map((o) => {
      if (o.id !== id) return o;
      out = { ...o, payMethod: method };
      return out;
    }));
    if (!out) throw new Error('NO_SUCH_ORDER');
    return clone(out);
  },

  async setPaid(id, paid, via){
    let out = null;
    commit('orders', K.orders, (list) => list.map((o) => {
      if (o.id !== id) return o;
      out = {
        ...o,
        paid: !!paid,
        paidAt: paid ? new Date().toISOString() : null,
        paidVia: paid ? (via || 'upi') : null,
      };
      return out;
    }));
    if (!out) throw new Error('NO_SUCH_ORDER');
    return clone(out);
  },

  // Stop order within a run. Unsequenced orders sort last.
  async sequence(runId, orderIds){
    commit('orders', K.orders, (list) => list.map((o) => {
      if (o.runId !== runId) return o;
      const i = orderIds.indexOf(o.id);
      return i < 0 ? o : { ...o, seq: i + 1 };
    }));
    return orders.forRun(runId);
  },
};
