export const catalog = {
  async categories(){ return clone((await DATA).categories); },
  async all(){ return clone((await DATA).products); },
  async byCat(catId){ return clone((await DATA).products.filter((p) => p.cat === catId)); },
  // In stock only. An offer on something that cannot be bought is
  // worse than no offer: it is a promise the shelf cannot keep.
  // The whole festival in one answer -- whether it is on, what to
  // call it, and the products -- so no screen has to hold a date
  // rule of its own. Off-season this returns { on: false } and the
  // home screen draws nothing.
  async festival(){
    const d = await DATA;
    const fest = d.festival;
    if (!festivalOn(fest, istDate())) return { on: false };
    const list = (fest.products || [])
      .map((id) => d.byId[id])
      .filter((p) => p && p.stock > 0);
    return { on: list.length > 0, id: fest.id, products: clone(list) };
  },
  async onOffer(limit){
    const all = (await DATA).products.filter((p) => p.offer && p.stock > 0);
    return clone(limit ? all.slice(0, limit) : all);
  },
  async byId(pid){ return clone((await DATA).byId[pid] || null); },

  async byIds(pids){
    const d = await DATA;
    const out = {};
    for (const id of pids) if (d.byId[id]) out[id] = clone(d.byId[id]);
    return out;
  },

  // Every word must match something -- the id, brand, any language of
  // the name, or a tag. Order does not matter, so "parle biscuit" and
  // "biscuit parle" find the same thing.
  async search(q, lang){
    const d = await DATA;
    const words = String(q || '').toLowerCase().trim().split(/\s+/).filter(Boolean);
    if (!words.length) return [];
    const hay = (p) => [
      p.brand, p.name.en, p.name[lang] || '', p.id, ...(p.tags || []),
    ].join(' ').toLowerCase();

    const hits = [];
    for (const p of d.products){
      const h = hay(p);
      if (!words.every((w) => h.indexOf(w) >= 0)) continue;
      const label = ((p.brand || '') + ' ' + p.name.en).toLowerCase();
      let score = 0;
      if (label.indexOf(words.join(' ')) === 0) score += 100;
      else if (label.indexOf(words.join(' ')) > 0) score += 40;
      if (words.every((w) => label.indexOf(w) >= 0)) score += 20;
      if (p.stock > 0) score += 5;
      hits.push({ p, score, len: label.length });
    }
    hits.sort((a, b) => b.score - a.score || a.len - b.len);
    return clone(hits.map((h) => h.p));
  },

  // "Goes well with" -- what the basket implies, from pairs.json.
  //
  // Scores add across the whole basket, so milk AND tea together push
  // sugar above anything either suggests alone. A named pair counts
  // for 3 and a category fallback for 1, which is what keeps the
  // specific knowledge (tea wants sugar) ahead of the generic
  // (snacks want drinks).
  //
  // Nothing here looks at what anyone actually bought -- there is no
  // history to mine. It is hand-written kitchen sense, and it is in a
  // data file so the shopkeeper can argue with it.
  async suggest(limit){
    const d = await DATA;
    const lines = read(K.cart, []);
    if (!lines.length) return [];

    const inCart = new Set(lines.map((l) => l.pid));
    const score = new Map();
    const bump = (pid, by) => {
      if (!pid || inCart.has(pid) || !d.byId[pid]) return;
      if (!d.byId[pid].stock) return;
      score.set(pid, (score.get(pid) || 0) + by);
    };

    for (const l of lines){
      const p = d.byId[l.pid];
      if (!p) continue;
      for (const pid of (d.pairs.byProduct[p.id] || [])) bump(pid, 3);
      for (const cat of (d.pairs.byCategory[p.cat] || [])){
        for (const q of d.products) if (q.cat === cat) bump(q.id, 1);
      }
    }

    // Ties broken by price, cheapest first: an add-on nobody asked for
    // should be an easy yes, not a second decision.
    const ranked = [...score.entries()]
      .sort((a, b) => b[1] - a[1] || d.byId[a[0]].price - d.byId[b[0]].price)
      .map(([pid]) => d.byId[pid]);

    // One of each IDEA, which is the product name and deliberately not
    // the brand. A strip has eight slots and each should be a different
    // thought: Bisleri 1 L and 2 L are one thought, and so are the Vim
    // and Exo dishwash bars, which a basket of soap was offering side
    // by side. Four names in this catalogue are shared that way --
    // dishwash bar, mango drink, drinking water, cola -- and in every
    // one of them the second is a wasted slot. Whichever ranked higher
    // wins; the other is still a search away.
    const seen = new Set();
    const out = [];
    for (const p of ranked){
      const key = p.name.en;
      if (seen.has(key)) continue;
      seen.add(key);
      out.push(p);
      if (out.length >= (limit || 8)) break;
    }
    return clone(out);
  },

  // ---- the Store's side ----

  // Everything, hidden products included, in shelf order: the Store's
  // Products screen. Customers never ask for this.
  async storeList(){
    const d = await DATA;
    const at = new Map(d.categories.map((c, i) => [c.id, i]));
    const pos = (p) => (at.has(p.cat) ? at.get(p.cat) : 99);
    return clone(Object.values(d.byId).sort((a, b) => pos(a) - pos(b)
      || (a.brand || '').localeCompare(b.brand || '')
      || a.name.en.localeCompare(b.name.en)));
  },

  // The Supabase backend can find its table missing. Storage here
  // cannot, so this always answers yes.
  async editsState(){ return 'ok'; },

  async refresh(){
    DATA = BASE.then((b) => withEdits(b, read(K.products, {})));
    await DATA;
    emit('catalog');
  },

  // Facade rule 3: a new product's id is minted HERE, never by the
  // screen. A photo arrives as a Blob the screen has already shrunk.
  async save(pid, fields, photo){
    const id = pid || mintProductId();
    const all = read(K.products, {});
    const edit = await makeEdit(pid, fields, all[id]);
    if (photo) edit.photo = await asDataUrl(photo);
    if (emptyEdit(edit)) delete all[id]; else all[id] = edit;
    if (!write(K.products, all)) throw new Error('STORAGE_FULL');
    await catalog.refresh();
    return clone((await DATA).byId[id] || null);
  },

  async setStock(pid, n){
    const d = await DATA;
    if (d.byId[pid]) d.byId[pid].stock = Math.max(0, n | 0);
    return clone(d.byId[pid] || null);
  },
};

// ---------------------------------------------------------------------
//  makeEdit -- what the Store form sent, turned into what is stored.
//  ONE function for both backends, so the checks cannot drift apart.
//  It throws a code; the screen turns the code into a sentence.
// ---------------------------------------------------------------------
const IN_STOCK = 20;
// The words data.pl refuses in catalog.json. The shop is pure veg and
// says so on every screen, and a name typed at the counter is the one
// road onto the shelf that the Perl check never sees.
const NOT_VEG = /\b(eggs?|chicken|mutton|fish|prawns?|bacon|meat)\b|अंड|चिकन|मांस|ઈંડ|ચિકન|માંસ/i;
const LANG_KEYS = ['en', 'hi', 'gu', 'mr'];
const names = (n) => Object.fromEntries(LANG_KEYS.map((l) => [l, (n && n[l]) || '']));
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

function tileFor(b, cat){
  const n = {};
  for (const p of b.products) if (p.cat === cat) n[p.tile] = (n[p.tile] || 0) + 1;
  return Object.keys(n).sort((x, y) => n[y] - n[x])[0] || 'packet';
}

export async function makeEdit(pid, f, prev){
  const b = await BASE;
  const base = pid ? b.byId[pid] || null : null;
  if (pid && !base && !(prev && prev.added)) throw new Error('NO_SUCH_PRODUCT');
  const name = names({});
  for (const l of LANG_KEYS) name[l] = String((f.name && f.name[l]) || '').trim().slice(0, 80);
  if (!name.en) throw new Error('NAME');
  if (Object.values(name).some((x) => NOT_VEG.test(x))) throw new Error('NOT_VEG');
  const n = Number(f.packN);
  if (!(n > 0 && n <= 100000) || !PACK_UNITS.includes(f.packU)) throw new Error('SIZE');
  if (!b.categories.some((c) => c.id === f.cat)) throw new Error('CAT');
  const price = Number(f.price);
  if (!Number.isInteger(price) || price < 1 || price > 100000) throw new Error('PRICE');
  let mrp = (f.mrp === '' || f.mrp == null) ? price : Number(f.mrp);
  if (!Number.isInteger(mrp) || mrp < 1 || mrp > 100000) throw new Error('MRP');
  // setprice.pl's rule: a price above the MRP raises the MRP to match.
  if (mrp < price) mrp = price;
  // Against the FILE, field by field. Only what differs is stored, so
  // a later correction to catalog.json still reaches every field the
  // shop never touched.
  const keep = (k, v) => (base && same(base[k] == null ? '' : base[k], v) ? null : v);
  return {
    added: !base,
    name: base && same(names(base.name), name) ? null : name,
    brand: keep('brand', String(f.brand || '').trim().slice(0, 40)),
    cat: keep('cat', f.cat),
    pack: keep('pack', { n, u: f.packU }),
    price: keep('price', price),
    mrp: keep('mrp', mrp),
    stock: f.inStock ? (base && base.stock > 0 ? null : IN_STOCK) : 0,
    hidden: !!f.hidden,
    photo: (prev && prev.photo) || null,
    tile: base ? null : ((prev && prev.tile) || tileFor(b, f.cat)),
  };
}

// An edit that changes nothing is deleted rather than stored: putting
// every field back the way the file has it IS taking the edit back.
export const emptyEdit = (e) => !e.added && !e.hidden && !e.photo
  && ['name', 'brand', 'cat', 'pack', 'price', 'mrp', 'stock'].every((k) => e[k] == null);

export const mintProductId = () =>
  'p-x' + Date.now().toString(36) + Math.random().toString(36).slice(2, 6);

const asDataUrl = (blob) => new Promise((res, rej) => {
  const r = new FileReader();
  r.onload = () => res(r.result);
  r.onerror = () => rej(new Error('PHOTO'));
  r.readAsDataURL(blob);
});

//
//  A line is {pid, qty} and NOTHING else -- in particular no price. A
//  cart that stores a price disagrees with itself the moment the
//  shopkeeper edits one, and it surfaces as "the cart total isn't the
//  confirmation total", which is unfixable once there are two sources
//  of truth. Price is resolved at render, and frozen into the order
//  line at placement, which is the one moment it must not move.
// ---------------------------------------------------------------------
export const cart = {
  async lines(){ return read(K.cart, []); },

  async setQty(pid, qty){
    return commit('cart', K.cart, (lines) => {
      const out = lines.filter((l) => l.pid !== pid);
      if (qty > 0) out.push({ pid, qty: Math.min(99, qty | 0) });
      return out;
    });
  },

  async add(pid, n = 1){
    const lines = read(K.cart, []);
    const cur = lines.find((l) => l.pid === pid);
    return cart.setQty(pid, (cur ? cur.qty : 0) + n);
  },

  async clear(){
    try { localStorage.removeItem(K.coupon); } catch {}
    return commit('cart', K.cart, () => []);
  },

  // The applied coupon, re-validated against the current code list on
  // every read. A code that is withdrawn from shop.json stops working
  // immediately, rather than living on in whoever's browser had it.
  async coupon(){
    const d = await DATA;
    return matchCoupon(read(K.coupon, null), d.coupons);
  },

  // Returns the matched coupon, or null if the code is not one of
  // ours. The caller shows the error; this just answers.
  async applyCoupon(code){
    const d = await DATA;
    const hit = matchCoupon(code, d.coupons);
    if (hit) { write(K.coupon, hit.code); }
    commit('cart', K.cart, (lines) => lines);   // repaint everything
    return hit;
  },

  async clearCoupon(){
    try { localStorage.removeItem(K.coupon); } catch {}
    commit('cart', K.cart, (lines) => lines);
    return null;
  },

  async totals(){
    const d = await DATA;
    return calcTotals(read(K.cart, []), d.byId, d.delivery, await cart.coupon(), d.offers);
  },
};

