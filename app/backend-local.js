const K = {
  cart: 'kirana.cart', orders: 'kirana.orders',
  runs: 'kirana.runs', profile: 'kirana.profile', seq: 'kirana.seq',
  coupon: 'kirana.coupon', places: 'kirana.places',
  products: 'kirana.products',
};
const REV = { cart: 'kirana.rev.cart', orders: 'kirana.rev.orders', runs: 'kirana.rev.runs' };

const clone = (v) => (v == null ? v : JSON.parse(JSON.stringify(v)));

// This browser's own edits, until a backend hands in others.
DATA = BASE.then((b) => withEdits(b, read(K.products, {})));

function read(key, fallback){
  try {
    const raw = localStorage.getItem(key);
    return raw == null ? clone(fallback) : JSON.parse(raw);
  } catch { return clone(fallback); }
}
function write(key, val){
  try { localStorage.setItem(key, JSON.stringify(val)); return true; }
  catch (e) { console.error('storage full or blocked', e); return false; }
}

// ---------------------------------------------------------------------
//  live -- cross-tab fan-out.
//
//  The `storage` event fires in every OTHER tab of the origin and
//  deliberately NOT in the one that wrote, so a single path cannot
//  serve both: the writer notifies itself directly.
// ---------------------------------------------------------------------
const subs = new Map();      // topic -> Set<cb>
const seen = new Map();      // topic -> last revision acted on

function emit(topic){
  for (const cb of subs.get(topic) || []){
    try { cb(); } catch (e) { console.error('subscriber', topic, e); }
  }
}

function commit(topic, key, mutate){
  // Re-read immediately before writing. Never hold a long-lived array
  // as the source of truth -- the other tab may have written since.
  const next = mutate(read(key, []));
  write(key, next);
  // A random tail so two writes in the same millisecond still differ,
  // and so an identical value still counts as a change.
  const rev = Date.now() + ':' + Math.random().toString(36).slice(2, 8);
  try { localStorage.setItem(REV[topic], rev); } catch {}
  seen.set(topic, rev);
  emit(topic);
  return next;
}

addEventListener('storage', (e) => {
  if (!e.key || e.key.indexOf('kirana.rev.') !== 0) return;
  const topic = e.key.slice('kirana.rev.'.length);
  if (!REV[topic]) return;
  if (seen.get(topic) === e.newValue) return;      // our own write, echoed
  seen.set(topic, e.newValue);
  emit(topic);
});

export const live = {
  subscribe(topic, cb){
    if (!subs.has(topic)) subs.set(topic, new Set());
    subs.get(topic).add(cb);
    return () => { const s = subs.get(topic); if (s) s.delete(cb); };
  },
};

