// =====================================================================
//  backend-local.js -- the whole app, backed by localStorage.
//
//  This is the reference implementation of the contract in store.js.
//  A Supabase version satisfies the same signatures and the swap is
//  one import line. Four rules make that true, and they are the reason
//  some of what follows looks more careful than localStorage needs:
//
//   1. EVERY method is async, even ones answered from memory.
//      A synchronous method means rewriting every call site the day it
//      becomes a network call.
//   2. Returns are deep-cloned. In Supabase a caller could not mutate
//      shared state, so here it must not be able to either.
//   3. Ids are minted HERE, never by the UI.
//   4. live.subscribe returns an unsubscribe function.
//
//  KNOWN LIMIT, written down rather than hoped away: two tabs writing
//  the same collection in the same instant can clobber each other,
//  because this stores whole arrays. commit() re-reads immediately
//  before writing, which narrows the window to microseconds, but does
//  not close it. Row-level writes are exactly what Supabase gives for
//  free, and this is half the argument for making the swap.
// =====================================================================


