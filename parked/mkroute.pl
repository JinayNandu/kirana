#!/usr/bin/perl
# Build app/data/routes.json from app/data/zones.json.
#
#   perl tools/mkroute.pl
#
# The stop ORDER is written down here by hand, because it is a claim
# about which lanes a tempo actually uses and that is the shopkeeper's
# knowledge, not something to derive from coordinates.
#
# The leg DURATIONS are a placeholder: straight-line distance times a
# 1.35 circuity factor at 33 km/h free flow. They are replaced by a
# one-off pass through OSRM once the geometry is baked in -- which is
# why `path` is null and the map draws a DASHED line until then. The
# dash is not decoration; it is the honest signal that the line is a
# sketch rather than a road.
use strict;
use warnings;
use JSON::PP;

my $PI = 4 * atan2(1, 1);
my $CIRCUITY = 1.35;          # straight line -> road
my $FREEFLOW = 9.17;          # m/s, about 33 km/h
my $DWELL    = 4;             # minutes standing at a stop

# The shop is on Devidas Road, in the NORTH of the delivery area. So
# the loop drops south-west to Yogi Nagar, sweeps the south (Vazira,
# Kastur Park, Shimpoli) and the core (Babhai, Chandavarkar, Vazira
# Naka), runs west out to Gorai, and comes home through Eksar, I.C.
# Colony and Mandapeshwar, which are on the doorstep.
#
# This order came from OSRM's trip solver, asked from the depot:
# 16.28 km / 26.8 min. It is a better STARTING POINT than a guess and
# it is still only that -- OSRM knows the road network, not which lanes
# a tempo actually uses, which turns are no-entry after dark, or where
# the driver can stand for four minutes. The shopkeeper corrects this
# list; nothing re-derives it.
#
# Re-solve it if the depot moves:
#   curl "https://router.project-osrm.org/trip/v1/driving/<lng,lat;...>\
#         ?source=first&roundtrip=true&overview=false"
my @CW = qw(
  yogi-nagar
  vazira kastur-park shimpoli
  babhai chandavarkar vazira-naka
  gorai-road gorai ashtavinayak
  eksar ic-colony mandapeshwar
);

sub metres {
  my ($a, $b) = @_;
  my $R  = 6371000;
  my $p1 = $a->[0] * $PI / 180;
  my $p2 = $b->[0] * $PI / 180;
  my $dp = ($b->[0] - $a->[0]) * $PI / 180;
  my $dl = ($b->[1] - $a->[1]) * $PI / 180;
  my $x  = sin($dp / 2) ** 2 + cos($p1) * cos($p2) * sin($dl / 2) ** 2;
  return 2 * $R * atan2(sqrt($x), sqrt(1 - $x));
}

my $here = $0; $here =~ s{[^/]+$}{};
my $root = ($here || './') . '../app/data/';

local $/;

# The shop is the depot -- the route starts and ends there. It lives in
# shop.json, not zones.json, because it is the shopkeeper's to edit.
open my $sf, '<:raw', $root . 'shop.json' or die "shop.json: $!\n";
my $shop = JSON::PP->new->decode(<$sf>);
close $sf;

open my $zf, '<:raw', $root . 'zones.json' or die "zones.json: $!\n";
my $z = JSON::PP->new->decode(<$zf>);
close $zf;

my %LOC;
for my $zone (@{ $z->{zones} }) {
  for my $l (@{ $zone->{localities} }) {
    $LOC{ $l->{id} } = { %$l, zoneId => $zone->{id} };
  }
}
for my $id (@CW) { die "unknown locality in route: $id\n" unless $LOC{$id} }

sub build {
  my ($id, $name, @order) = @_;
  my @stops = ({
    id => 's-depot', seq => 0, kind => 'depot',
    zoneId => undef, localityId => undef,
    name => $shop->{name}, ll => $shop->{ll},
    legSec => 0, dwellMin => 0,
  });
  my $prev = $shop->{ll};
  my $seq  = 1;
  for my $lid (@order) {
    my $l = $LOC{$lid};
    my $d = metres($prev, $l->{ll}) * $CIRCUITY;
    push @stops, {
      id => 's-' . $lid, seq => $seq++, kind => 'stop',
      zoneId => $l->{zoneId}, localityId => $lid,
      name => $l->{name}, ll => $l->{ll},
      legSec => int($d / $FREEFLOW + 0.5), dwellMin => $DWELL,
    };
    $prev = $l->{ll};
  }
  my $back = metres($prev, $shop->{ll}) * $CIRCUITY;
  push @stops, {
    id => 's-depot-in', seq => $seq, kind => 'depot',
    zoneId => undef, localityId => undef,
    name => $shop->{name}, ll => $shop->{ll},
    legSec => int($back / $FREEFLOW + 0.5), dwellMin => 0,
  };
  return { id => $id, name => $name, stops => \@stops, path => undef };
}

my @routes = (
  build('loop-cw',  'Clockwise loop',     @CW),
  build('loop-acw', 'Anticlockwise loop', reverse @CW),
);

for my $r (@routes) {
  my ($sec, $dwell) = (0, 0);
  for my $s (@{ $r->{stops} }) { $sec += $s->{legSec}; $dwell += $s->{dwellMin} }
  printf "%-10s %2d stops  %5.1f min free-flow  + %d min dwell\n",
    $r->{id}, scalar(@{ $r->{stops} }) - 2, $sec / 60, $dwell;
}

my @now = localtime;
my $stamp = sprintf('%04d-%02d-%02d', $now[5] + 1900, $now[4] + 1, $now[3]);

my $out = {
  note => 'Generated by tools/mkroute.pl. legSec is a straight-line placeholder '
        . 'at 33 km/h with a 1.35 circuity factor, NOT a measured road time, and '
        . 'path is null so the map draws a dashed sketch. Both are replaced by the '
        . 'one-off OSRM pass. Stop order is hand-written and is the shopkeeper to confirm.',
  generated => $stamp,
  routes => \@routes,
};

open my $of, '>:raw', $root . 'routes.json' or die "write routes.json: $!\n";
print $of JSON::PP->new->canonical->pretty->encode($out);
close $of;
print "wrote app/data/routes.json\n";
